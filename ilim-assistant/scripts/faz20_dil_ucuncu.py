_TAMAM = (
    " Bu kart okunur. El satırı derlemez, kurmaz ve çalıştırmaz."
)


def parcalar() -> list[tuple[str, str, list[str], str]]:
    out: list[tuple[str, str, list[str], str]] = []
    for kok, baslik, metinler in _DIL:
        if len(metinler) != len(_BOLUM):
            raise RuntimeError(kok)
        for (anahtar, ad_tr, ad_sade), metin in zip(_BOLUM, metinler):
            aliases = [
                f"{kok} {ad_tr}",
                f"{kok} {ad_tr} nedir",
                f"{kok} {ad_sade}",
                f"{kok} {ad_sade} nedir",
                f"{baslik.lower()} {ad_tr}",
                f"{baslik.lower()} {ad_tr} nedir",
            ]
            temiz: list[str] = []
            for ad in aliases:
                if ad not in temiz:
                    temiz.append(ad)
            if len(metin) < 80:
                metin = metin.rstrip() + _TAMAM
            out.append((f"{kok}_{anahtar}", f"{baslik} {ad_tr}", temiz, metin))
    return out
