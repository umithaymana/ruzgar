def _p(doc: Document, text: str, *, bold: bool = False) -> None:
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold = bold
    run.font.size = Pt(11)
    run.font.name = "Calibri"


def _bullets(doc: Document, items: list[str]) -> None:
    for it in items:
        para = doc.add_paragraph(style="List Number")
        run = para.add_run(it)
        run.font.size = Pt(11)
        run.font.name = "Calibri"


